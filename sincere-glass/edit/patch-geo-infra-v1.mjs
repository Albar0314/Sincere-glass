#!/usr/bin/env node
/**
 * Sincere Glass - SOP v3.0 Site-Wide SEO/GEO Infrastructure & Cluster Typo Patch
 * Marker: SG-GEO-INFRA-V1
 *
 * Actions:
 *   1. Fixes "starphire-vs-low-iron-glass" -> "starphire-vs-low-iron" in src/lib/blog-clusters.ts
 *   2. Creates dynamic route handler src/app/llms.txt/route.ts (indexes products, tools,
 *      pillars, and all live blog articles dynamically from registries)
 *   3. Updates src/app/robots.ts to explicitly allow major AI search/crawling bots
 *      (OAI-SearchBot, ChatGPT-User, PerplexityBot, ClaudeBot, Google-Extended, Applebot-Extended)
 *   4. Upgrades articleJsonLd in src/components/blog/BlogArticleLayout.tsx with
 *      entity-linked `about` and `mentions` (including standard/brand URIs + Wikidata
 *      references where appropriate) while keeping @graph backward-compatible
 *
 * Usage:
 *   node edit\patch-geo-infra-v1.mjs --dry-run
 *   node edit\patch-geo-infra-v1.mjs
 *   npm run build
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DRY_RUN = process.argv.includes("--dry-run");
const MARKER = "SG-GEO-INFRA-V1";

function log(msg) {
  console.log((DRY_RUN ? "[DRY-RUN] " : "") + msg);
}

function detectEol(text) {
  return text.includes("\r\n") ? "\r\n" : "\n";
}

function backupOnce(absPath, raw) {
  if (DRY_RUN) return;
  const bak = absPath + ".bak";
  if (!fs.existsSync(bak) && fs.existsSync(absPath)) {
    fs.writeFileSync(bak, raw, "utf8");
    log("[bak]     " + path.relative(ROOT, bak));
  }
}

function writeFileSafe(absPath, content) {
  if (DRY_RUN) {
    log("[dry-run] would write " + path.relative(ROOT, absPath));
    return;
  }
  fs.mkdirSync(path.dirname(absPath), { recursive: true });
  fs.writeFileSync(absPath, content, "utf8");
  log("[updated] " + path.relative(ROOT, absPath));
}

// ---------------------------------------------------------------------------
// 1. Fix slug typo in src/lib/blog-clusters.ts
// ---------------------------------------------------------------------------
function patchBlogClusters() {
  const rel = "src/lib/blog-clusters.ts";
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) {
    throw new Error("Missing " + rel);
  }
  const raw = fs.readFileSync(abs, "utf8");
  if (!raw.includes("starphire-vs-low-iron-glass")) {
    log("[skip]    " + rel + " already uses starphire-vs-low-iron");
    return;
  }
  backupOnce(abs, raw);
  const updated = raw.replaceAll("starphire-vs-low-iron-glass", "starphire-vs-low-iron");
  writeFileSafe(abs, updated);
}

