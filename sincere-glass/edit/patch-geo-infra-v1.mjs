// ---------------------------------------------------------------------------
// 3. Update src/app/robots.ts with explicit AI search & crawler rules
// ---------------------------------------------------------------------------
function patchRobots() {
  const rel = "src/app/robots.ts";
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) {
    throw new Error("Missing " + rel);
  }
  const raw = fs.readFileSync(abs, "utf8");
  const eol = detectEol(raw);

  if (raw.includes("OAI-SearchBot") || raw.includes("PerplexityBot")) {
    log("[skip]    " + rel + " already includes AI crawler rules");
    return;
  }

  const anchor = /(\s*\{\s*userAgent:\s*"\*",\s*allow:\s*"\/",\s*disallow:\s*\[[^\]]*\],?\s*\},)/;
  if (!anchor.test(raw)) {
    throw new Error("Could not match wildcard rule in " + rel);
  }

  const aiBots = [
    "OAI-SearchBot",
    "ChatGPT-User",
    "PerplexityBot",
    "ClaudeBot",
    "Google-Extended",
    "Applebot-Extended",
  ];

  const extraRules = aiBots
    .map((bot) =>
      [
        "      {",
        '        userAgent: "' + bot + '",',
        '        allow: "/",',
        '        disallow: ["/api/", "/_next/"],',
        "      },",
      ].join(eol)
    )
    .join(eol);

  backupOnce(abs, raw);
  const updated = raw.replace(anchor, "$1" + eol + extraRules);
  writeFileSafe(abs, updated);
}

// ---------------------------------------------------------------------------
// 4. Upgrade articleJsonLd in BlogArticleLayout.tsx with about & mentions entities
// ---------------------------------------------------------------------------
function patchArticleJsonLd() {
  const rel = "src/components/blog/BlogArticleLayout.tsx";
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) {
    throw new Error("Missing " + rel);
  }
  const raw = fs.readFileSync(abs, "utf8");
  const eol = detectEol(raw);

  if (raw.includes(MARKER)) {
    log("[skip]    " + rel + " already patched with " + MARKER);
    return;
  }

  const helperBlock = [
    "  // " + MARKER + ": Entity graph linking for GEO / AI search disambiguation",
    "  const ENTITY_URI_MAP: Record<string, string> = {",
    '    "low iron glass": "https://www.wikidata.org/wiki/Q1069727",',
    '    "ultra-clear glass": "https://www.wikidata.org/wiki/Q1069727",',
    '    "tempered glass": "https://www.wikidata.org/wiki/Q239891",',
    '    "laminated glass": "https://www.wikidata.org/wiki/Q1458565",',
    '    "insulated glass": "https://www.wikidata.org/wiki/Q1191295",',
    '    "low-e glass": "https://www.wikidata.org/wiki/Q2643083",',
    '    "astm c1036": "https://www.astm.org/c1036-21.html",',
    '    "astm c1048": "https://www.astm.org/c1048-18.html",',
    '    "astm e1300": "https://www.astm.org/e1300-16.html",',
    '    "astm e2190": "https://www.astm.org/e2190-19.html",',
    '    "en 12150": "https://standards.cencenelec.eu/",',
    '    "en 1279": "https://standards.cencenelec.eu/",',
    '    "en 14449": "https://standards.cencenelec.eu/",',
    '    "en 14179": "https://standards.cencenelec.eu/",',
    '    "starphire": "https://www.wikidata.org/wiki/Q7601532",',
    '    "optiwhite": "https://www.wikidata.org/wiki/Q1458565",',
    '    "saint-gobain": "https://www.wikidata.org/wiki/Q164974",',
    '    "guardian glass": "https://www.wikidata.org/wiki/Q1554873",',
    "  };",
    "",
    "  const toEntityNode = (label: string) => {",
    "    const clean = label.trim();",
    "    const uri = ENTITY_URI_MAP[clean.toLowerCase()];",
    "    return uri",
    "      ? { '@type': 'Thing', name: clean, sameAs: uri }",
    "      : { '@type': 'Thing', name: clean };",
    "  };",
    "",
    "  const aboutEntities = [",
    "    toEntityNode(article.targetKeyword),",
    "    ...(article.tags || []).slice(0, 2).map(toEntityNode),",
    "  ];",
    "",
    "  const mentionCandidates = [",
    "    ...(article.secondaryKeywords || []).slice(0, 4),",
    "    ...(article.relatedProductSlugs || []).map((s) => s.replace(/-/g, ' ')),",
    "  ];",
    "  const seenNames = new Set<string>(aboutEntities.map((e) => String(e.name).toLowerCase()));",
    "  const mentionEntities = [];",
    "  for (const cand of mentionCandidates) {",
    "    const key = cand.trim().toLowerCase();",
    "    if (!key || seenNames.has(key)) continue;",
    "    seenNames.add(key);",
    "    mentionEntities.push(toEntityNode(cand));",
    "    if (mentionEntities.length >= 6) break;",
    "  }",
    "",
  ].join(eol);

  const graphTarget =
    "      author: {" +
    eol +
    "        '@type': 'Person'," +
    eol +
    "        name: article.author.name," +
    eol +
    "        url: article.author.url," +
    eol +
    "      }," +
    eol +
    "      publisher: { '@id': `${SITE}/#organization` },";

  const graphReplacement =
    graphTarget +
    eol +
    "      about: aboutEntities," +
    (mentionEntitiesStrPlaceHolder(eol));

  // Build exact replacement string without dynamic template evaluation issues
  const graphReplacementExact =
    graphTarget +
    eol +
    "      about: aboutEntities," +
    eol +
    "      ...(mentionEntities.length > 0 ? { mentions: mentionEntities } : {}),";

  const fnStartRe = /(export function articleJsonLd\([\s\S]*?\n  const graph: object\[\] = \[)/;
  if (!fnStartRe.test(raw) || !raw.includes(graphTarget)) {
    throw new Error("Could not locate articleJsonLd graph anchors in " + rel);
  }

  backupOnce(abs, raw);
  let updated = raw.replace(fnStartRe, helperBlock + "$1");
  updated = updated.replace(graphTarget, graphReplacementExact);
  writeFileSafe(abs, updated);
}

function mentionEntitiesStrPlaceHolder(eol) {
  return eol + "      ...(mentionEntities.length > 0 ? { mentions: mentionEntities } : {}),";
}

log("=== Running " + MARKER + " ===");
patchBlogClusters();
createLlmsTxtRoute();
patchRobots();
patchArticleJsonLd();
if (!DRY_RUN) {
  console.log("Done! Run `npm run build` next to verify.");
}
