// edit/patch-localized-link.mjs
// 1. Create src/components/LocalizedLink.tsx — a drop-in replacement for next/link
//    that automatically prefixes href with current locale.
// 2. Replace `import Link from "next/link"` with `import Link from "@/components/LocalizedLink"`
//    across all .tsx/.ts files in src/components and src/app (excluding es mirrors).
//
// Usage: node edit\patch-localized-link.mjs

import fs from 'fs';
import path from 'path';

const root = process.cwd();

// ============================================================
// Step 1: Create LocalizedLink.tsx
// ============================================================
const localizedLinkContent = `"use client";

import Link, { type LinkProps } from "next/link";
import { usePathname } from "next/navigation";
import { forwardRef, type AnchorHTMLAttributes, type ReactNode } from "react";
import { getLocaleFromPath, localizedPath, DEFAULT_LOCALE } from "@/lib/i18n";

type Props = Omit<LinkProps, "href"> &
  Omit<AnchorHTMLAttributes<HTMLAnchorElement>, keyof LinkProps> & {
    href: LinkProps["href"];
    children?: ReactNode;
  };

/**
 * Drop-in replacement for Next.js <Link> that automatically prefixes the href
 * with the current locale, if the user is browsing a non-default locale.
 *
 * - "/about" on an ES page → "/es/about"
 * - "/about" on an EN page → "/about" (unchanged)
 * - External URLs, hash links, and non-string hrefs pass through unchanged.
 */
const LocalizedLink = forwardRef<HTMLAnchorElement, Props>(function LocalizedLink(
  { href, children, ...rest },
  ref,
) {
  const pathname = usePathname() ?? "/";
  const locale = getLocaleFromPath(pathname);

  let resolvedHref: LinkProps["href"] = href;
  if (typeof href === "string" && href.startsWith("/") && locale !== DEFAULT_LOCALE) {
    resolvedHref = localizedPath(href, locale);
  }

  return (
    <Link ref={ref} href={resolvedHref} {...rest}>
      {children}
    </Link>
  );
});

export default LocalizedLink;
`;

const localizedLinkPath = path.join(root, 'src/components/LocalizedLink.tsx');
fs.writeFileSync(localizedLinkPath, localizedLinkContent, 'utf-8');
console.log(`✅ Created: src/components/LocalizedLink.tsx`);

// ============================================================
// Step 2: Replace imports across src/components and src/app
// ============================================================
function walkTsx(dir, callback) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    const rel = path.relative(root, full);

    // Skip mirror directories
    if (rel.split(path.sep).includes('_i18n')) continue;
    // Skip src/app/es subtree (regenerated by translate-all)
    const parts = rel.split(path.sep);
    if (parts[0] === 'src' && parts[1] === 'app' && parts[2] === 'es') continue;

    if (e.isDirectory()) {
      walkTsx(full, callback);
    } else if (/\.(tsx|ts)$/.test(e.name)) {
      callback(full);
    }
  }
}

// Matches:
//   import Link from "next/link";
//   import Link from 'next/link';
//   (with or without trailing semicolon)
// Does NOT match:
//   import Link, { LinkProps } from "next/link";  ← kept, handled below
//   import NextLink from "next/link";
const simpleImportPattern = /import\s+Link\s+from\s+["']next\/link["']\s*;?/g;

// Matches: import Link, { ...other } from "next/link";
// We need to keep the { ...other } side and redirect only Link
const combinedImportPattern = /import\s+Link\s*,\s*\{([^}]+)\}\s+from\s+["']next\/link["']\s*;?/g;

let changedCount = 0;
let totalScanned = 0;

function processFile(file) {
  totalScanned++;
  // Skip LocalizedLink itself and type-definition files
  const basename = path.basename(file);
  if (basename === 'LocalizedLink.tsx') return;

  let content = fs.readFileSync(file, 'utf-8');
  const original = content;

  // Case A: `import Link, { X } from "next/link"` → split into two imports
  content = content.replace(combinedImportPattern, (_match, otherNames) => {
    return `import Link from "@/components/LocalizedLink";\nimport {${otherNames}} from "next/link";`;
  });

  // Case B: `import Link from "next/link"` → use wrapper
  content = content.replace(simpleImportPattern, `import Link from "@/components/LocalizedLink";`);

  if (content !== original) {
    fs.writeFileSync(file, content, 'utf-8');
    changedCount++;
    console.log(`  ✍️  ${path.relative(root, file)}`);
  }
}

console.log(`\n🔍 Scanning src/components/ and src/app/ for Link imports...`);
walkTsx(path.join(root, 'src/components'), processFile);
walkTsx(path.join(root, 'src/app'), processFile);

console.log(`\n📊 Scanned ${totalScanned} files, updated ${changedCount}`);

