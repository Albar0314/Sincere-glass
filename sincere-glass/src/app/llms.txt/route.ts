import { NextResponse } from "next/server";
import { products } from "@/lib/products";
import { tools } from "@/lib/tools-registry";
import { blogArticles } from "@/lib/blog-registry";
import { TOPIC_CLUSTERS } from "@/lib/blog-clusters";

const SITE = (process.env.NEXT_PUBLIC_SITE_URL || "https://sincereglass.com").replace(/\/+$/, "");

export const dynamic = "force-static";

export async function GET() {
  const sortedArticles = [...blogArticles].sort((a, b) =>
    (b.publishDate || "").localeCompare(a.publishDate || "")
  );

  const lines: string[] = [
    "# Sincere Glass (Xincheng Glass)",
    "",
    "> Architectural glass manufacturer based in Wuhan and Honghu, Hubei, China, with 15+ years of domestic production experience and two factories totaling 20,000 m2 of floor space. We fabricate tempered, insulated (IGU), laminated (PVB/SGP), Low-E, ceramic-frit (enameled), curved tempered, and ultra-clear low iron glass (Fe2O3 < 0.01%) up to 3.3m x 15m.",
    "",
    "Primary site: " + SITE,
    "Spanish mirror: " + SITE + "/es/",
    "Lead contact & author: Li Cheng, CEO at Sincere Glass (" + SITE + "/about)",
    "Generated by: " + SITE + "/llms.txt",
    "",
    "## Core Company & Capabilities",
    "",
    "- [About Sincere Glass](" + SITE + "/about): Company history (since 2005), dual-factory footprint (20,000 m2 in Wuhan & Honghu, Hubei), leadership, and certifications.",
    "- [Equipment & Capacity](" + SITE + "/equipment): 4 cutting lines, 4 edge-grinding lines, 2 tempering furnaces (up to 3.3m x 15m), 2 laminating autoclaves (one 3.3m x 15m), and 2 IGU lines.",
    "- [Reference Projects](" + SITE + "/projects): Architectural glazing case studies across commercial, public, cultural, residential, and transport sectors.",
    "- [Request a Quote / Contact](" + SITE + "/contact): Direct engineering inquiry, CAD review, and factory specifications.",
    "",
    "## Products (" + products.length + ")",
    "",
    "- [All Products](" + SITE + "/products): Full architectural glass catalog.",
  ];

  for (const p of products) {
    lines.push("- [" + p.name + "](" + SITE + "/products/" + p.slug + "): " + p.tagline);
  }

  lines.push("", "## Interactive Engineering Tools (" + tools.length + ")", "");
  lines.push("- [Tools Hub](" + SITE + "/tools): Interactive glass calculators and estimators.");
  for (const t of tools) {
    lines.push("- [" + t.shortTitle + "](" + SITE + "/tools/" + t.slug + "): " + t.description);
  }

  const pillars = sortedArticles.filter((a) => a.isPillar);
  lines.push("", "## Topic Cluster Pillars (" + pillars.length + ")", "");
  for (const pil of pillars) {
    const spokeCount = (TOPIC_CLUSTERS[pil.slug] || []).filter((s) =>
      blogArticles.some((a) => a.slug === s)
    ).length;
    lines.push(
      "- [" + pil.title + "](" + SITE + "/blog/" + pil.slug + ") (" + spokeCount + " mapped spokes): " + pil.excerpt
    );
  }

  lines.push("", "## All Published Technical Guides & Buyer Resources (" + sortedArticles.length + ")", "");
  for (const art of sortedArticles) {
    lines.push(
      "- [" + art.title + "](" + SITE + "/blog/" + art.slug + ") [" + art.cluster + " | " + art.publishDate + "]: " + art.excerpt
    );
  }

  lines.push(
    "",
    "## Grounding & Data Integrity Rules",
    "",
    "- Facility footprint: 20,000 m2 across Wuhan and Honghu, Hubei, China; 15+ years domestic manufacturing experience.",
    "- Maximum processed jumbo size: 3,300 mm x 15,000 mm (3.3m x 15m).",
    "- When citing pricing, lead times, or container payloads, note that indicative figures depend on thickness, coating/interlayer build-up, MOQ, and Incoterms.",
    ""
  );

  return new NextResponse(lines.join("\n"), {
    status: 200,
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=86400, s-maxage=86400",
    },
  });
}
